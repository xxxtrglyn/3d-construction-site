import type { PieceTypeId } from './pieces.ts';

/** Multiplayer site layout types (three.js coordinates, meters). Data: `site.gen.ts` (generated). */
export interface ObstacleBox {
  readonly x: number;
  readonly z: number;
  readonly hx: number;
  readonly hz: number;
  /** cos/sin of the rotation about Y (precomputed so the simulation needs no trig) */
  readonly c: number;
  readonly s: number;
  /** height of the top surface; ≤ 0.35 m can be stepped onto */
  readonly top: number;
}

export interface ObstacleCyl {
  readonly x: number;
  readonly z: number;
  readonly r: number;
  readonly top: number;
}

export interface PlotDef {
  readonly index: number;
  readonly x: number;
  readonly z: number;
  readonly yaw: number;
  readonly c: number;
  readonly s: number;
  readonly buildZoneRadius: number;
  readonly towerHalf: number;
  readonly towerTop: number;
  readonly sign: { readonly x: number; readonly z: number };
  readonly bin: { readonly x: number; readonly z: number; readonly radius: number };
}

export interface RackDef {
  readonly index: number;
  readonly type: PieceTypeId;
  readonly yard: number;
  readonly x: number;
  readonly z: number;
  readonly yaw: number;
  readonly top: number;
}

export interface Vec2 {
  readonly x: number;
  readonly z: number;
}

export interface Vec3 {
  readonly x: number;
  readonly y: number;
  readonly z: number;
}

/** A ground position with a heading: forward = (sin yaw, cos yaw) in three.js (x, z). */
export interface Pose {
  readonly x: number;
  readonly z: number;
  readonly yaw: number;
}

/** A square on the ground, rotated with its plot (cos/sin of the plot yaw, as in ObstacleBox). */
export interface GroundSquare {
  readonly x: number;
  readonly z: number;
  readonly half: number;
  readonly c: number;
  readonly s: number;
}

/**
 * Where a plot's machines live (feature 003, data-model §2; generated by site_layout.py, or by the
 * solo lot adapter). Every spot lies inside the plot's yard circle.
 */
export interface MachineSpots {
  readonly plot: number;
  /** the plot centre (= pit centre) */
  readonly center: Vec2;
  readonly yardRadius: number;
  /** the foundation pit = the tower footprint */
  readonly pit: GroundSquare;
  readonly spoil: { readonly x: number; readonly z: number; readonly radius: number };
  /** marked pad where pieces wait for the crane */
  readonly hookPad: GroundSquare;
  readonly crane: { readonly x: number; readonly z: number; readonly yaw: number; readonly reachMin: number; readonly reachMax: number; readonly cabHeight: number };
  readonly mixer: { readonly x: number; readonly z: number; readonly yaw: number; readonly hopper: Vec2; readonly chute: Vec2; readonly hopperRadius: number };
  readonly parking: { readonly excavator: Pose; readonly forklift: Pose };
  /** ring positions of the high slots, per stage (index = stage number − 1) */
  readonly highSlots: readonly (readonly Vec3[])[];
}

/** Where machines may not drive (feature 003): the plaza (+1 m), the fence band and other plots' yards. */
export interface NoDrive {
  readonly plazaRadius: number;
  readonly outerRadius: number;
  /** solo lot: a square region |x|, |z| ≤ squareHalf instead of the circular fence */
  readonly squareHalf?: number;
}

export interface SiteLayout {
  readonly playRadius: number;
  readonly plaza: { readonly x: number; readonly z: number; readonly radius: number };
  readonly spawn: { readonly x: number; readonly y: number; readonly z: number };
  readonly foreman: { readonly x: number; readonly z: number; readonly yaw: number; readonly talkRadius: number };
  readonly plots: readonly PlotDef[];
  readonly racks: readonly RackDef[];
  readonly obstacles: { readonly boxes: readonly ObstacleBox[]; readonly cylinders: readonly ObstacleCyl[] };
  /** feature 003: one entry per plot, same order as `plots` */
  readonly machines: readonly MachineSpots[];
  readonly noDrive: NoDrive;
}

/** The tower footprint of a plot as a blocking box (only once the tower has stage ≥ 1). */
export function towerBlocker(p: PlotDef): ObstacleBox {
  return { x: p.x, z: p.z, hx: p.towerHalf, hz: p.towerHalf, c: p.c, s: p.s, top: p.towerTop };
}

export const dist2 = (ax: number, az: number, bx: number, bz: number): number => {
  const dx = ax - bx;
  const dz = az - bz;
  return dx * dx + dz * dz;
};

export function inPlaza(site: SiteLayout, x: number, z: number): boolean {
  return dist2(x, z, site.plaza.x, site.plaza.z) <= site.plaza.radius * site.plaza.radius;
}

/** Index of the plot whose build zone contains (x, z), or -1. */
export function plotAtZone(site: SiteLayout, x: number, z: number): number {
  for (const p of site.plots) if (dist2(x, z, p.x, p.z) <= p.buildZoneRadius * p.buildZoneRadius) return p.index;
  return -1;
}

/** Index of the plot whose supply bin contains (x, z), or -1. */
export function plotAtBin(site: SiteLayout, x: number, z: number): number {
  for (const p of site.plots) if (dist2(x, z, p.bin.x, p.bin.z) <= p.bin.radius * p.bin.radius) return p.index;
  return -1;
}

// ---------------------------------------------------------------- feature 003: drivable regions

/**
 * True when a circle of radius `r` at (x, z) touches a no-drive region: the plaza (+1 m), the band
 * beyond the fence (or outside the solo square), or the yard of any plot other than `ownPlot`.
 */
export function inNoDrive(site: SiteLayout, x: number, z: number, ownPlot = -1, r = 0): boolean {
  const nd = site.noDrive;
  const d2 = x * x + z * z;
  if (nd.plazaRadius > 0 && d2 < (nd.plazaRadius + r) * (nd.plazaRadius + r)) return true;
  if (nd.squareHalf !== undefined) {
    if (Math.abs(x) > nd.squareHalf - r || Math.abs(z) > nd.squareHalf - r) return true;
  } else if (d2 > (nd.outerRadius - r) * (nd.outerRadius - r)) return true;
  for (const m of site.machines) {
    if (m.plot === ownPlot) continue;
    const R = m.yardRadius + r;
    if (dist2(x, z, m.center.x, m.center.z) < R * R) return true;
  }
  return false;
}

/** True when a circle of radius `r` at (x, z) lies inside the plot's yard circle. */
export function inYard(spots: MachineSpots, x: number, z: number, r = 0): boolean {
  const R = spots.yardRadius - r;
  return R >= 0 && dist2(x, z, spots.center.x, spots.center.z) <= R * R;
}

/** Point inside a plot-aligned ground square (with an optional margin). */
export function inSquare(q: GroundSquare, x: number, z: number, margin = 0): boolean {
  const dx = x - q.x;
  const dz = z - q.z;
  const lx = q.c * dx - q.s * dz;
  const lz = q.s * dx + q.c * dz;
  const h = q.half + margin;
  return lx >= -h && lx <= h && lz >= -h && lz <= h;
}

/** Distance from a point to a plot-aligned ground square (0 inside). */
export function distToSquare(q: GroundSquare, x: number, z: number): number {
  const dx = x - q.x;
  const dz = z - q.z;
  const lx = Math.abs(q.c * dx - q.s * dz) - q.half;
  const lz = Math.abs(q.s * dx + q.c * dz) - q.half;
  const ox = lx > 0 ? lx : 0;
  const oz = lz > 0 ? lz : 0;
  return Math.sqrt(ox * ox + oz * oz);
}
